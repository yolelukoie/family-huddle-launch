/** HTML-escape a string for use in attribute values. */
function escHtml(s) {
  return s
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

/**
 * Pure transform: given the dist/index.html template and a page descriptor,
 * return a new HTML string with social meta tags injected and the marker present.
 */
export function transformHtml(template, page) {
  let html = template;

  // Strip tags that should not appear in generated pages
  html = html.replace(/<title>[\s\S]*?<\/title>/gi, '');
  html = html.replace(/<meta\s+name="description"[^>]*\/?>/gi, '');
  html = html.replace(/<meta\s+name="author"[^>]*\/?>/gi, '');
  html = html.replace(/<meta\s+property="og:[^"]*"[^>]*\/?>/gi, '');
  html = html.replace(/<meta\s+name="twitter:[^"]*"[^>]*\/?>/gi, '');
  html = html.replace(/<link\s+rel="canonical"[^>]*\/?>/gi, '');

  const eTitle = escHtml(page.title);
  const eDesc = escHtml(page.description);
  const eUrl = escHtml(page.url);

  const lines = [
    MARKER,
    `<title>${eTitle}</title>`,
    `<meta name="description" content="${eDesc}" />`,
    `<link rel="canonical" href="${eUrl}" />`,
    `<meta property="og:site_name" content="YourLangCoach" />`,
    `<meta property="og:type" content="website" />`,
    `<meta property="og:url" content="${eUrl}" />`,
    `<meta property="og:title" content="${eTitle}" />`,
    `<meta property="og:description" content="${eDesc}" />`,
    `<meta property="og:image" content="${OG_IMAGE}" />`,
    `<meta property="og:image:type" content="image/png" />`,
    `<meta property="og:image:width" content="1200" />`,
    `<meta property="og:image:height" content="630" />`,
    `<meta property="og:image:alt" content="YourLangCoach logo" />`,
    `<meta property="og:locale" content="en_US" />`,
    `<meta name="twitter:card" content="summary_large_image" />`,
    `<meta name="twitter:title" content="${eTitle}" />`,
    `<meta name="twitter:description" content="${eDesc}" />`,
    `<meta name="twitter:image" content="${OG_IMAGE}" />`,
  ];

  const block = lines.join('\n  ');
  html = html.replace('</head>', `  ${block}\n</head>`);
  return html;
}

/**
 * Write content to filePath, respecting the marker-based skip/overwrite policy.
 * Returns true if the file was written, false if it was skipped.
 */
function writeFile(filePath, content) {
  mkdirSync(dirname(filePath), { recursive: true });

  if (existsSync(filePath)) {
    const existing = readFileSync(filePath, 'utf8');
    if (!existing.includes(MARKER)) {
      console.warn(
        `[generate-social-pages] SKIPPED (no marker, not overwriting): ${filePath}`,
      );
      return false;
    }
  }

  writeFileSync(filePath, content, 'utf8');
  return true;
}

/** Verify a generated file meets all acceptance criteria. */
function verify(filePath) {
  const content = readFileSync(filePath, 'utf8');
  let ok = true;

  const titleCount = (content.match(/<title>/gi) || []).length;
  if (titleCount !== 1) {
    console.error(
      `[generate-social-pages] FAIL: expected 1 <title>, got ${titleCount} in ${filePath}`,
    );
    ok = false;
  }

  const ogTitleCount = (content.match(/property="og:title"/gi) || []).length;
  if (ogTitleCount !== 1) {
    console.error(
      `[generate-social-pages] FAIL: expected 1 og:title, got ${ogTitleCount} in ${filePath}`,
    );
    ok = false;
  }

  const ogImageMatch = content.match(/property="og:image"\s+content="([^"]+)"/i);
  if (!ogImageMatch || !ogImageMatch[1].startsWith('https://')) {
    console.error(
      `[generate-social-pages] FAIL: og:image missing or not https:// in ${filePath}`,
    );
    ok = false;
  }

  if (!content.includes(MARKER)) {
    console.error(`[generate-social-pages] FAIL: marker missing in ${filePath}`);
    ok = false;
  }

  const hasModuleScript =
    content.includes('type="module"') && /src="\/assets\//.test(content);
  if (!hasModuleScript) {
    console.error(
      `[generate-social-pages] FAIL: no <script type="module" src="/assets/..."> in ${filePath}`,
    );
    ok = false;
  }

  const hasFamilyHuddle =
    /<title>[^<]*Family Huddle[^<]*<\/title>/i.test(content) ||
    /<meta\s+(?:name|property)="[^"]*"\s+content="[^"]*Family Huddle[^"]*"/i.test(content);
  if (hasFamilyHuddle) {
    console.error(
      `[generate-social-pages] FAIL: "Family Huddle" found in title or meta in ${filePath}`,
    );
    ok = false;
  }

  return ok;
}

async function main() {
  const templatePath = join(DIST, 'index.html');
  if (!existsSync(templatePath)) {
    console.error(
      '[generate-social-pages] ERROR: dist/index.html not found. Run vite build first.',
    );
    process.exit(1);
  }

  const template = readFileSync(templatePath, 'utf8');
  const writtenFiles = [];
  let failed = false;

  for (const page of PAGES) {
    const generated = transformHtml(template, page);
    const targets = [
      join(DIST, `${page.path}.html`),
      join(DIST, page.path, 'index.html'),
    ];

    for (const target of targets) {
      const written = writeFile(target, generated);
      if (written) {
        const rel = target.slice(DIST.length + 1);
        console.log(`[generate-social-pages] wrote ${rel}`);
        writtenFiles.push(target);
      }
    }
  }

  for (const filePath of writtenFiles) {
    if (!verify(filePath)) {
      failed = true;
    }
  }

  if (failed) {
    console.error(
      '[generate-social-pages] Verification failed — see errors above.',
    );
    process.exit(1);
  }

  console.log(
    `[generate-social-pages] Done. ${writtenFiles.length} files verified and written.`,
  );
}

if (__filename === process.argv[1]) {
  main();
}
